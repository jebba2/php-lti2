#!/usr/bin/env php
<?php

declare(strict_types=1);

// One-shot setup for this example: generates a tool key pair and a
// simulator ("fake platform") key pair, and writes config/config.php
// wiring them together. Safe to re-run — it regenerates everything from
// scratch, so any launches/state mid-flight will need to start over.

require __DIR__ . '/../vendor/autoload.php';

use PhpLti\Lti1p3\Security\Jwt\KeyPairGenerator;

const TOOL_KID = 'tool-key-1';
const SIMULATOR_KID = 'simulator-key-1';

$keysDir = __DIR__ . '/../working/keys';
if (!is_dir($keysDir) && !mkdir($keysDir, 0700, true) && !is_dir($keysDir)) {
    fwrite(STDERR, "Could not create {$keysDir}\n");
    exit(1);
}

$generator = new KeyPairGenerator();
$toolKid = TOOL_KID;
$simulatorKid = SIMULATOR_KID;

foreach ([$toolKid, $simulatorKid] as $kid) {
    $keyPair = $generator->generate($kid);
    file_put_contents($keysDir . "/{$kid}.private.pem", $keyPair->privateKey);
    chmod($keysDir . "/{$kid}.private.pem", 0600);
    file_put_contents($keysDir . "/{$kid}.public.pem", $keyPair->publicKey);
}

$config = <<<PHP
<?php

declare(strict_types=1);

// Generated by bin/setup.php — safe to regenerate at any time by re-running it.
return [
    'tool_base_url' => 'http://localhost:8000',
    'simulator_base_url' => 'http://localhost:8001',
    'client_id' => 'demo-client-1',
    'deployment_id' => 'demo-deployment-1',
    'tool_kid' => '{$toolKid}',
    'simulator_kid' => '{$simulatorKid}',
    // Optional: audience ("aud") for the client assertion sent to the token
    // endpoint. Omit it to use the token url, which is the spec default and
    // what nearly every platform expects. Set it only for a platform that
    // demands a fixed audience of its own; the simulator honours it too.
    // 'platform_audience' => 'https://platform.example.com/api/lti/authorize',
];
PHP;

file_put_contents(__DIR__ . '/../config/config.php', $config);

echo "Setup complete.\n\n";
echo "Generated tool and simulator RSA key pairs in working/keys/.\n";
echo "Wrote config/config.php.\n\n";
echo "Next steps (run each in its own terminal, from the example/ directory):\n";
echo "  1. PHP_CLI_SERVER_WORKERS=4 php -S localhost:8000 -t public\n";
echo "  2. PHP_CLI_SERVER_WORKERS=4 php -S localhost:8001 simulator/router.php\n";
echo "  3. Open http://localhost:8001/ in your browser and click through.\n\n";
echo "PHP_CLI_SERVER_WORKERS matters here, not just for speed: the AGS demo has the tool\n";
echo "call the simulator's /token endpoint, which calls *back* into the tool's /jwks.php to\n";
echo "verify the client assertion. With the default single-worker php -S, that second call\n";
echo "has nowhere to be served (the one worker is still busy with the first request) and the\n";
echo "whole thing hangs until PHP's execution time limit kills it.\n";
